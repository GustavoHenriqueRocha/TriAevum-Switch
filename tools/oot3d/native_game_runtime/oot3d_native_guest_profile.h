#pragma once

// Lightweight per-function profile of guest code, to find the functions worth
// a native override (oot3d_native_guest_overrides).
//
// Enabled by a config file (on Switch,
// sdmc:/switch/oot3dre/config/guest_profile; on desktop, the path in
// TRIAEVUM_GUEST_PROFILE). When on, the block-entry callback is called on
// every block ("all blocks" mode, which the runtime already supports): it
// counts the block entry, adds the time since the last entry to the previous
// block (system counter, 19.2 MHz on Switch) and forwards to the original
// callback only the PCs that were hooks, so the game behaves exactly as
// without the profiler. When off, nothing changes on the hot path.
//
// Periodic output in logs/guest_profile.txt: per-function histogram (block
// entries and exclusive time), plus the hottest blocks. Names come from
// config/guest_functions.txt (generated by summarize_guest_profile.py
// --export-function-map); without it, aggregation uses PCs only.
//
// Config file format: "key=value" lines, all optional:
//   sample_every=4         measure 1 of every N host frames (1 = all); on
//                          the others the original callback is restored and
//                          the game runs at normal speed
//   dump_frames=900        host frames between writes (0 = never)
//   top_functions=250      per-function lines in the report
//   top_blocks=400         per-block lines in the report
//   window=0               1 = reset counters after each write
//   output=<path>          report file
//   functions=<path>       entry->name map
//   max_gap_us=200         gaps longer than this are not attributed to a block
//                          (the guest left for the host: SVC, end of frame...)

#include "oot3d_guest_spike_profile.h"
#include "recomp/a32_runtime.h"

#include <cstddef>
#include <cstdint>
#include <filesystem>
#include <functional>
#include <iosfwd>
#include <span>
#include <string>
#include <vector>

namespace Oot3dNativeGame {

struct GuestProfileOptions {
    uint32_t SampleEveryFrames = 4U;
    uint32_t DumpEveryHostFrames = 900U;
    uint32_t TopFunctions = 250U;
    uint32_t TopBlocks = 400U;
    bool Window = false;
    uint32_t MaxGapMicroseconds = 200U;
    std::filesystem::path OutputPath;
    std::filesystem::path FunctionMapPath;
};

class GuestBlockProfiler {
public:
    // Reads the config file. false if it does not exist (profiler off).
    static bool LoadConfig(const std::filesystem::path& path,
                           const std::filesystem::path& defaultOutput,
                           const std::filesystem::path& defaultFunctionMap,
                           GuestProfileOptions* options);

    bool Start(const GuestProfileOptions& options, uint32_t codeBase,
               uint32_t codeSize);
    ~GuestBlockProfiler();

    // Spike profile (config/guest_spike_ms, oot3d_guest_spike_profile.h):
    // after Start; measures every frame (sample_every becomes 1) and writes
    // spikes to `log` (append) and the summary to `summary` (rewrite) every
    // `flushFrames` host frames and at the end.
    bool EnableSpikes(const GuestSpikeConfig& config,
                      const std::filesystem::path& log,
                      const std::filesystem::path& summary,
                      uint32_t flushFrames = 150U);
    [[nodiscard]] bool SpikesEnabled() const noexcept { return mSpikeOn; }
    void FlushSpikes();
    [[nodiscard]] bool Active() const noexcept { return mActive; }

    // Original callback and the PCs on which it must keep being called.
    // forwardAll: the original callback already expected every block.
    void Chain(oot3d::recomp::a32::BlockEntryCallback callback, void* user,
               std::span<const uint32_t> hooks, bool forwardAll);

    static void OnBlockEntry(uint32_t pc, oot3d::recomp::a32::GuestState& state,
                             oot3d::recomp::a32::MemoryBus& memory, void* user);

    // For native overrides: would the profiler forward some PC in
    // [first, last] to the original callback? (then they decline). Otherwise
    // the override runs and MarkNative counts one entry at `pc` and attributes
    // to it the time until the next block entry (the native version's time).
    [[nodiscard]] bool ForwardsRange(uint32_t first, uint32_t last) const noexcept;
    void MarkNative(uint32_t pc) noexcept;

    // Called once per host frame; writes at the configured interval and
    // says whether the next frame should be measured (profiler callback installed).
    bool OnHostFrame(uint64_t hostFrame);
    // The profiler callback was removed or restored: do not attribute the gap.
    void Interrupt() noexcept { mLastSlot = UINT32_MAX; }
    bool WriteReport(uint64_t hostFrame);

    // Extra text at the end of the report (for example, the native override
    // counters).
    void SetAppendix(std::function<void(std::ostream&)> appendix) {
        mAppendix = std::move(appendix);
    }

private:
    static uint64_t Ticks() noexcept;
    static uint64_t TicksPerSecond() noexcept;
    bool IsHook(uint32_t pc) const noexcept;
    void Note(uint32_t pc, uint64_t now) noexcept;
    void RegisterWithGuestOverrides() noexcept;
    void LoadFunctionMap();
    void Reset() noexcept;

    GuestProfileOptions mOptions;
    bool mActive = false;
    uint32_t mBase = 0U;
    uint32_t mSlots = 0U;
    std::vector<uint32_t> mCounts;
    std::vector<uint64_t> mTicks;
    uint64_t mTotalEntries = 0U;
    uint64_t mOutside = 0U;
    uint64_t mGaps = 0U;
    uint64_t mGapTicks = 0U;
    uint64_t mMaxGapTicks = 0U;
    uint64_t mLastTicks = 0U;
    uint32_t mLastSlot = UINT32_MAX;
    uint64_t mStartTicks = 0U;
    uint64_t mStartFrame = 0U;
    uint64_t mSampledFrames = 0U;
    bool mSampling = true;
    uint64_t mLastDumpFrame = 0U;
    bool mFrameSeen = false;

    oot3d::recomp::a32::BlockEntryCallback mCallback = nullptr;
    void* mCallbackUser = nullptr;
    bool mForwardAll = false;
    std::vector<uint32_t> mHooks;
    std::vector<uint64_t> mHookFilter;

    std::vector<std::pair<uint32_t, std::string>> mFunctions;
    bool mFunctionsLoaded = false;
    std::function<void(std::ostream&)> mAppendix;

    GuestSpikeProfile mSpike;
    bool mSpikeOn = false;
    std::filesystem::path mSpikeLog;
    std::filesystem::path mSpikeSummary;
    uint32_t mSpikeFlushFrames = 150U;
    uint64_t mSpikeLastFlush = 0U;
    uint64_t mSpikeEntriesStart = 0U;
    bool mSpikeFrameSeen = false;
    std::string mSpikeText;
};

} // namespace Oot3dNativeGame
