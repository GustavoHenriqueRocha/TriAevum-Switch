def t_tokens(b):
    i, t = 0, []
    while i < len(b):
        if b[i] == 0x7f and i+1 < len(b):
            c = b[i+1]; n = T_ARGS.get(c, 0); t.append(('c', c, b[i+2:i+2+n])); i += 2+n
        else:
            t.append(('t', b[i])); i += 1
    return t
