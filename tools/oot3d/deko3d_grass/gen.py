#!/usr/bin/env python3
"""Compiles the deko3d grass shaders (SWITCH_PORT.md, "Grass on deko3d") with uam and
generates runtime/three_ds_recomp/src/fast/backends/gfx_deko3d_grass_dksh.h.

Three stages for config/grass_lod = 0 (test.9's grass): the vertex program and two
fragment variants, one that writes the PICA depth (GRASS_EXPLICIT_DEPTH) and one that
leaves depth to the rasterizer. Three more for config/grass_lod on: the tuft pass
(grass_tuft_vsh.glsl) and the far and near blade programs (grass_lod_vsh.glsl), which
share grass_lod_common.glsl through `#include "..."` lines this script pastes in.
They do not go in deko3d.pack, which holds PICA texts keyed by their hash.

Usage: python3 tools/oot3d/deko3d_grass/gen.py [--uam /opt/devkitpro/tools/bin/uam]
"""
import argparse
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "deko3d_scanout"))
from gen import array, compile_stage  # noqa: E402

ROOT = HERE.parents[2]
OUT = ROOT / "runtime/three_ds_recomp/src/fast/backends/gfx_deko3d_grass_dksh.h"
# (array name, stage, source, defines)
STAGES = [
    ("kGrassVertexDksh", "vert", "grass_vsh.glsl", []),
    ("kGrassFragmentDksh", "frag", "grass_fsh.glsl", []),
    ("kGrassFragmentDepthDksh", "frag", "grass_fsh.glsl", ["GRASS_EXPLICIT_DEPTH"]),
    ("kGrassTuftVertexDksh", "vert", "grass_tuft_vsh.glsl", []),
    ("kGrassLodFarVertexDksh", "vert", "grass_lod_vsh.glsl", []),
    ("kGrassLodNearVertexDksh", "vert", "grass_lod_vsh.glsl", ["GRASS_LOD_NEAR"]),
]


def expand(source):
    """The source with each `#include "name"` line replaced by that file (beside it)."""
    lines = []
    for line in source.read_text().splitlines(keepends=True):
        stripped = line.strip()
        if stripped.startswith("#include"):
            name = stripped.split('"')[1]
            lines.extend(expand(source.parent / name).splitlines(keepends=True))
            if not lines[-1].endswith("\n"):
                lines[-1] += "\n"
        else:
            lines.append(line)
    return "".join(lines)


def with_defines(source, defines, workdir, name):
    """The source with `#define`s after its #version line (uam has no -D) and its
    includes pasted in (uam has no #include)."""
    text = expand(source)
    if not defines and text == source.read_text():
        return source
    lines = text.splitlines(keepends=True)
    if not lines or not lines[0].startswith("#version"):
        raise SystemExit(f"{source}: the first line must be #version")
    extra = "".join(f"#define {define} 1\n" for define in defines)
    path = Path(workdir) / f"{name}.glsl"
    path.write_text(lines[0] + extra + "".join(lines[1:]))
    return path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--uam", default="/opt/devkitpro/tools/bin/uam")
    args = parser.parse_args()
    arrays = []
    sizes = []
    with tempfile.TemporaryDirectory() as workdir:
        for name, stage, source, defines in STAGES:
            path = with_defines(HERE / source, defines, workdir, name)
            data = compile_stage(args.uam, stage, path, workdir)
            arrays.append(array(name, data))
            sizes.append(f"{name} {len(data)} B")
    OUT.write_text("\n".join([
        "#pragma once",
        "// Generated by tools/oot3d/deko3d_grass/gen.py (uam) from",
        "// tools/oot3d/deko3d_grass/grass_{vsh,fsh,tuft_vsh,lod_vsh,lod_common}.glsl. Do not edit by hand.",
        "#include <cstdint>",
        "",
        "namespace Fast::Deko3d {",
        *arrays,
        "} // namespace Fast::Deko3d",
        "",
    ]))
    print(f"{OUT}: " + ", ".join(sizes))


if __name__ == "__main__":
    main()
