#!/usr/bin/env python3
"""Compiles the deko3d simple shadow programs (SWITCH_PORT.md, "Simple shadow") with
uam and generates runtime/three_ds_recomp/src/fast/backends/gfx_deko3d_player_shadow_dksh.h.

The flattened meshes' vertex stage is the PICA program of each of Link's draws, so only
the fragment stage is built for them; the cover triangle (method "cover") and the floor
quad (method "texture") have both stages here. None goes in deko3d.pack, which holds
PICA texts keyed by their hash.

Usage: python3 tools/oot3d/deko3d_shadow/gen.py [--uam /opt/devkitpro/tools/bin/uam]
"""
import argparse
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "deko3d_scanout"))
from gen import array, compile_stage  # noqa: E402

ROOT = HERE.parents[2]
OUT = ROOT / "runtime/three_ds_recomp/src/fast/backends/gfx_deko3d_player_shadow_dksh.h"
PROGRAMS = (
    ("frag", "player_shadow_fsh.glsl", "kPlayerShadowFragmentDksh"),
    ("vert", "player_shadow_cover_vsh.glsl", "kPlayerShadowCoverVertexDksh"),
    ("vert", "player_shadow_floor_vsh.glsl", "kPlayerShadowFloorVertexDksh"),
    ("frag", "player_shadow_floor_fsh.glsl", "kPlayerShadowFloorFragmentDksh"),
)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--uam", default="/opt/devkitpro/tools/bin/uam")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as workdir:
        compiled = [(name, compile_stage(args.uam, stage, HERE / source, workdir))
                    for stage, source, name in PROGRAMS]
    OUT.write_text("\n".join([
        "#pragma once",
        "// Generated by tools/oot3d/deko3d_shadow/gen.py (uam) from",
        "// tools/oot3d/deko3d_shadow/player_shadow_*.glsl. Do not edit by hand.",
        "#include <cstdint>",
        "",
        "namespace Fast::Deko3d {",
        *(array(name, data) for name, data in compiled),
        "} // namespace Fast::Deko3d",
        "",
    ]))
    for name, data in compiled:
        print(f"{OUT}: {name} {len(data)} B")


if __name__ == "__main__":
    main()
