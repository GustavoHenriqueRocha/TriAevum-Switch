#!/usr/bin/env python3
"""Compiles the deko3d simple shadow fragment program (SWITCH_PORT.md, "Simple shadow")
with uam and generates
runtime/three_ds_recomp/src/fast/backends/gfx_deko3d_player_shadow_dksh.h.

The vertex stage is the PICA program of each of Link's draws, so only the fragment
stage is built here. It does not go in deko3d.pack, which holds PICA texts keyed by
their hash.

Usage: python3 tools/oot3d/deko3d_shadow/gen.py [--uam /opt/devkitpro/tools/bin/uam]
"""
import argparse
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "deko3d_scanout"))
from gen import array, compile_stage  # noqa: E402

ROOT = HERE.parents[2]
OUT = ROOT / "runtime/three_ds_recomp/src/fast/backends/gfx_deko3d_player_shadow_dksh.h"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--uam", default="/opt/devkitpro/tools/bin/uam")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as workdir:
        data = compile_stage(args.uam, "frag", HERE / "player_shadow_fsh.glsl", workdir)
    OUT.write_text("\n".join([
        "#pragma once",
        "// Generated by tools/oot3d/deko3d_shadow/gen.py (uam) from",
        "// tools/oot3d/deko3d_shadow/player_shadow_fsh.glsl. Do not edit by hand.",
        "#include <cstdint>",
        "",
        "namespace Fast::Deko3d {",
        array("kPlayerShadowFragmentDksh", data),
        "} // namespace Fast::Deko3d",
        "",
    ]))
    print(f"{OUT}: kPlayerShadowFragmentDksh {len(data)} B")


if __name__ == "__main__":
    main()
